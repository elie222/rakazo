import { existsSync } from "node:fs";
import PDFDocument from "pdfkit";
import type { Fund, InvestUser, PensionUser, YearReport } from "../data.js";
import { KIND_LABEL, statementRows } from "../data.js";

const FONT_CANDIDATES = [
  process.env.HARNESS_LAB_FONT,
  "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf",
  "/usr/share/fonts/dejavu/DejaVuSans.ttf",
  "/Library/Fonts/Arial Unicode.ttf",
  "/System/Library/Fonts/Supplemental/Arial.ttf",
];
const HEBREW_FONT = FONT_CANDIDATES.find((p) => p && existsSync(p));
const HEBREW = /[֐-׿]/;

/**
 * Hebrew is written in visual order, as in many right-to-left PDFs: text extraction
 * therefore returns it reversed, while the numbers and English labels extract cleanly.
 */
function visual(s: string): string {
  if (!HEBREW.test(s)) return s;
  return s
    .split(" ")
    .map((w) => (HEBREW.test(w) ? [...w].reverse().join("") : w))
    .reverse()
    .join(" ");
}

type Row = [label: string, value: string];

interface Doc {
  titleHe: string;
  titleEn: string;
  subtitle: string[];
  rows: Row[];
  table?: { head: string[]; rows: string[][] };
  footer: string;
}

function render(doc: Doc): Promise<Buffer> {
  return new Promise((resolve, reject) => {
    const pdf = new PDFDocument({
      size: "A4",
      margin: 50,
      info: {
        Title: doc.titleEn,
        Producer: "harness-lab",
        CreationDate: new Date("2026-01-15T08:00:00Z"),
      },
    });
    const chunks: Buffer[] = [];
    pdf.on("data", (c: Buffer) => chunks.push(c));
    pdf.on("end", () => resolve(Buffer.concat(chunks)));
    pdf.on("error", reject);

    pdf.font("Helvetica-Bold").fontSize(20).text(doc.titleEn);
    if (HEBREW_FONT)
      pdf.font(HEBREW_FONT).fontSize(16).text(visual(doc.titleHe), { align: "right" });
    pdf.moveDown();
    pdf.font("Helvetica").fontSize(11);
    for (const line of doc.subtitle) pdf.text(line);
    pdf.moveDown();
    for (const [label, value] of doc.rows) {
      const y = pdf.y;
      pdf.font("Helvetica").text(label, 50, y, { width: 300, continued: false });
      pdf.font("Helvetica-Bold").text(value, 350, y, { width: 190, align: "right" });
      pdf.moveDown(0.3);
    }
    if (doc.table) {
      pdf.moveDown();
      const col = 490 / doc.table.head.length;
      const line = (cells: string[], bold: boolean) => {
        const y = pdf.y;
        cells.forEach((c, i) => {
          pdf
            .font(bold ? "Helvetica-Bold" : "Helvetica")
            .text(c, 50 + i * col, y, { width: col - 6 });
        });
        pdf.moveDown(0.2);
      };
      line(doc.table.head, true);
      for (const r of doc.table.rows) line(r, false);
    }
    pdf.moveDown(2).font("Helvetica").fontSize(8).fillColor("#666").text(doc.footer);
    pdf.end();
  });
}

const money = (n: number) =>
  n.toLocaleString("en-US", { minimumFractionDigits: 2, maximumFractionDigits: 2 });
const pct = (n: number) => `${n.toFixed(2)}%`;

export function pensionReportLines(_user: PensionUser, _fund: Fund, rep: YearReport): Row[] {
  return [
    ["Opening balance (NIS)", money(rep.openingBalance)],
    ["Deposits during the year (NIS)", money(rep.deposits)],
    ["Nominal return for the year", pct(rep.returnPct)],
    ["Management fee from deposits", pct(rep.feeFromDepositsPct)],
    ["Management fee from accumulated balance", pct(rep.feeFromBalancePct)],
    ["Closing balance (NIS)", money(rep.closingBalance)],
  ];
}

export function pensionReportPdf(user: PensionUser, fund: Fund, rep: YearReport): Promise<Buffer> {
  const kind = KIND_LABEL[fund.kind];
  return render({
    titleEn: `Annual report ${rep.year} - ${kind.en}`,
    titleHe: `דוח שנתי ${rep.year} - ${kind.he}`,
    subtitle: [
      `Kedem Pensions Ltd. (fictional) - lab document, not a real statement`,
      `Member: ${user.nameEn}   ID ending ${user.idNumber.slice(-4)}`,
      `Product: ${fund.nameEn}`,
      `Reporting period: 01/01/${rep.year} - 31/12/${rep.year}`,
    ],
    rows: pensionReportLines(user, fund, rep),
    footer: "Synthetic data generated by harness-lab. Past returns do not indicate future returns.",
  });
}

export function statementPdf(user: InvestUser, month: string): Promise<Buffer> {
  const rows = statementRows(user, month);
  const net = rows.reduce((s, r) => s + r.amount, 0);
  return render({
    titleEn: `Account statement ${month}`,
    titleHe: `דף חשבון ${month}`,
    subtitle: [
      `Tavor Investment House (fictional)`,
      `Account holder: ${user.nameEn}`,
      `Username: ${user.username}`,
    ],
    rows: [["Net cash movement (NIS)", money(net)]],
    table: {
      head: ["Date", "Description", "Amount (NIS)"],
      rows: rows.map((r) => [r.date, r.description, money(r.amount)]),
    },
    footer: "Synthetic data generated by harness-lab.",
  });
}

export function quarterlyPdf(user: InvestUser, quarter: string): Promise<Buffer> {
  const q = user.quarters.find((x) => x.quarter === quarter);
  if (!q) throw new Error(`no quarter ${quarter}`);
  return render({
    titleEn: `Quarterly report ${quarter}`,
    titleHe: `דוח רבעוני ${quarter}`,
    subtitle: [`Tavor Investment House (fictional)`, `Account holder: ${user.nameEn}`],
    rows: [
      ["Portfolio return for the quarter", pct(q.returnPct)],
      ["Portfolio value at quarter end (NIS)", money(q.endValue)],
      ["Deposits (NIS)", money(q.deposits)],
      ["Management and custody fees (NIS)", money(q.fees)],
    ],
    footer: "Synthetic data generated by harness-lab.",
  });
}

/** Minimal text extractor for pdfkit output (tests and fixtures). Falls back to pdftotext elsewhere. */
export async function extractPdfText(buf: Buffer): Promise<string> {
  const { inflateSync } = await import("node:zlib");
  const raw = buf.toString("latin1");
  const out: string[] = [];
  for (const m of raw.matchAll(/stream\r?\n([\s\S]*?)\r?\nendstream/g)) {
    let data: string;
    try {
      data = inflateSync(Buffer.from(m[1]!, "latin1")).toString("latin1");
    } catch {
      continue;
    }
    for (const t of data.matchAll(/\[?((?:<[0-9a-fA-F]*>\s*-?[\d.]*\s*)+)\]?\s*T[Jj]/g)) {
      const parts = [...t[1]!.matchAll(/<([0-9a-fA-F]*)>/g)].map((h) =>
        Buffer.from(h[1]!, "hex").toString("latin1"),
      );
      out.push(parts.join(""));
    }
  }
  return out.join("\n");
}
