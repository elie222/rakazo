import type { PluginMarketplaceCatalog, PluginMarketplaceEntry } from "@rakazo/contracts";
import { comparePlugins, matchesPluginQuery, pluginCategory } from "@rakazo/core";
import { z } from "zod";
import type { PluginCompleteness, PluginTextReader } from "./plugin-connectors.js";
import { classifyPluginFiles, parsePluginSource } from "./plugin-connectors.js";
import { fetchSafeWebText } from "./web-ssrf.js";

const REGISTRIES = [
  {
    name: "Cursor",
    repository: "https://github.com/cursor/plugins",
    path: ".cursor-plugin/marketplace.json",
    manifest: ".cursor-plugin/plugin.json",
    // Every listed plugin is vendored in the registry repo, so its file list tells its parts.
    componentIndex: null,
  },
  {
    name: "xAI",
    repository: "https://github.com/xai-org/plugin-marketplace",
    path: ".grok-plugin/marketplace.json",
    manifest: ".grok-plugin/plugin.json",
    // Generated by the registry for each pinned plugin, including ones hosted elsewhere.
    componentIndex: ".grok-plugin/plugin-index.json",
  },
];
type Registry = (typeof REGISTRIES)[number];
const MANIFEST_TTL_MS = 60 * 60_000;
const CATALOG_TTL_MS = 10 * 60_000;
const MANIFEST_CONCURRENCY = 16;
const entrySchema = z.object({
  name: z.string().trim().min(1).max(120),
  description: z.string().max(4000).optional(),
  keywords: z.array(z.string().max(120)).max(50).optional(),
  category: z.string().trim().min(1).max(60).optional().catch(undefined),
  homepage: z.string().url().max(2048).optional().catch(undefined),
  domains: z.array(z.string().max(253)).max(20).optional().catch(undefined),
  source: z.union([
    z.string().max(2048),
    z.object({
      source: z.literal("url"),
      url: z.string().max(2048),
      sha: z.string().regex(/^[a-f0-9]{40}$/),
      path: z.string().max(2048).optional(),
    }),
    z.object({ type: z.literal("local"), path: z.string().startsWith("./").max(2048) }),
  ]),
});

/** Public indexes are discovery hints, never installation authority. The
 * separate preview/digest gate validates and pins the selected package. */
export function parsePluginMarketplace(
  raw: string,
  registry: { name: string; repository: string },
): { entries: PluginMarketplaceEntry[]; skipped: number } {
  const index: unknown = JSON.parse(raw);
  if (
    !index ||
    typeof index !== "object" ||
    !("plugins" in index) ||
    !Array.isArray(index.plugins) ||
    index.plugins.length > 1000
  ) {
    throw new Error("Invalid marketplace index");
  }
  const entries: PluginMarketplaceEntry[] = [];
  const seen = new Set<string>();
  let skipped = 0;
  for (const candidate of index.plugins) {
    const parsed = entrySchema.safeParse(candidate);
    if (!parsed.success) {
      skipped++;
      continue;
    }
    const entry = parsed.data;
    try {
      const source = entry.source;
      const from =
        typeof source === "string"
          ? source.startsWith("https://")
            ? source
            : `${registry.repository}#${source.replace(/^\.\//, "")}`
          : !("url" in source)
            ? `${registry.repository}#${source.path.slice(2)}`
            : source.path
              ? `${source.url}#${source.path.replace(/^\.?\//, "")}`
              : source.url;
      const ref = parsePluginSource(from);
      if (new URL(ref.gitUrl).hostname !== "github.com") throw new Error("Unsupported plugin host");
      if (typeof source !== "string" && "sha" in source && ref.ref && ref.ref !== source.sha)
        throw new Error("Conflicting plugin pin");
      const pin = typeof source !== "string" && "sha" in source ? source.sha : ref.ref;
      const suffix = ref.subdir ? `#${ref.subdir}` : "";
      const installedSource = ref.gitUrl + suffix;
      const installSource = ref.gitUrl + (pin ? `@${pin}` : "") + suffix;
      if (seen.has(installSource)) {
        skipped++;
        continue;
      }
      seen.add(installSource);
      entries.push({
        id: `${registry.name}:${installSource}`,
        name: entry.name,
        displayName: displayName(entry.name),
        description: entry.description ?? "",
        keywords: entry.keywords ?? [],
        category: entry.category?.toLowerCase() ?? null,
        logo: null,
        homepage: entry.homepage ?? null,
        domains: entry.domains ?? [],
        registry: registry.name,
        source: installSource,
        installedSource,
        hasConnector: false,
        skillCount: 0,
      });
    } catch {
      skipped++;
    }
  }
  return { entries, skipped };
}

const manifestSchema = z.object({
  displayName: z.string().trim().min(1).max(120).optional().catch(undefined),
  category: z.string().trim().min(1).max(60).optional().catch(undefined),
  logo: z
    .string()
    .regex(/^(?!\/)(?!.*\.\.)[\w./-]+\.(svg|png|jpe?g|webp)$/i)
    .max(512)
    .optional()
    .catch(undefined),
});

const componentIndexSchema = z.object({
  plugins: z.record(
    z.string(),
    z.object({
      sha: z.string().optional(),
      components: z.record(z.string(), z.array(z.object({ description: z.string().optional() }))),
    }),
  ),
});
const INDEX_SKILL_PARTS = ["skills", "agents", "commands"];

/** Hosted MCP servers and skill-like parts install; anything else in the index does not.
 * The index cannot show credential placeholders or skill companion files; preview does. */
function classifyIndexed(
  components: Record<string, Array<{ description?: string }>>,
): PluginCompleteness | null {
  let skillCount = 0;
  let connectors = 0;
  for (const [kind, parts] of Object.entries(components)) {
    if (INDEX_SKILL_PARTS.includes(kind)) skillCount += parts.length;
    else if (kind === "mcpServers" && parts.every((part) => part.description === "http"))
      connectors += parts.length;
    else if (parts.length) return null;
  }
  return connectors || skillCount ? { hasConnector: connectors > 0, skillCount } : null;
}

function parseManifest(text: string): z.infer<typeof manifestSchema> | undefined {
  try {
    return manifestSchema.safeParse(JSON.parse(text)).data;
  } catch {
    return undefined;
  }
}

function displayName(name: string): string {
  return name
    .split(/[-_\s]+/)
    .filter(Boolean)
    .map((word) => word[0]!.toUpperCase() + word.slice(1))
    .join(" ");
}

const publicRead: PluginTextReader = async (url, maxBytes, signal) =>
  (await fetchSafeWebText(url, { maxBytes, signal })).body;

/** Cache is per API router instance; failures are never cached. Concurrent
 * requests share one bounded fetch, without sharing an actor's abort signal. */
export function createPluginMarketplace(read: PluginTextReader = publicRead) {
  const cache = new Map<
    string,
    { expires: number; data: ReturnType<typeof parsePluginMarketplace> }
  >();
  const pending = new Map<string, Promise<ReturnType<typeof parsePluginMarketplace>>>();
  /** Sources whose preview failed; they are left out of browse until this time. */
  const unreadable = new Map<string, number>();
  const files = new Map<string, { expires: number; text: string | null }>();
  const trees = new Map<string, { expires: number; paths: string[]; sizes: Map<string, number> }>();
  const cachedText = async (url: string, maxBytes: number, signal: AbortSignal) => {
    const cached = files.get(url);
    if (cached && cached.expires > Date.now()) return cached.text;
    try {
      const text = await read(url, maxBytes, signal);
      files.set(url, { text, expires: Date.now() + MANIFEST_TTL_MS });
      return text;
    } catch (error) {
      // Only a confirmed missing file is an answer; any other failure is retried next time.
      if (error instanceof Error && error.message === "Request failed: HTTP 404")
        files.set(url, { text: null, expires: Date.now() + MANIFEST_TTL_MS });
      return undefined;
    }
  };
  /** One recursive listing per registry repo; GitHub's API is rate limited, so it is kept for an hour. */
  async function repoTree(
    registry: Registry,
  ): Promise<{ paths: string[]; sizes: Map<string, number> }> {
    const cached = trees.get(registry.name);
    if (cached && cached.expires > Date.now()) return cached;
    const repo = new URL(registry.repository).pathname;
    const tree = JSON.parse(
      await read(
        `https://api.github.com/repos${repo}/git/trees/HEAD?recursive=1`,
        8_000_000,
        AbortSignal.timeout(15_000),
      ),
    ) as { truncated?: boolean; tree?: Array<{ path: string; type: string; size?: number }> };
    if (tree.truncated || !Array.isArray(tree.tree)) throw new Error("Registry tree is incomplete");
    const blobs = tree.tree.filter((entry) => entry.type === "blob");
    const listing = {
      paths: blobs.map((entry) => entry.path),
      sizes: new Map(blobs.map((entry) => [entry.path, entry.size ?? 0])),
    };
    trees.set(registry.name, { ...listing, expires: Date.now() + MANIFEST_TTL_MS });
    return listing;
  }
  /** Vendored plugins describe their title, category and logo in a manifest beside them, and
   * their MCP config decides whether the connector installs. Plugins that would not install
   * completely, or whose parts cannot be told, are left out. */
  async function withDetails(
    registry: Registry,
    entries: PluginMarketplaceEntry[],
  ): Promise<PluginMarketplaceEntry[]> {
    const raw = `https://raw.githubusercontent.com${new URL(registry.repository).pathname}/HEAD/`;
    const prefix = `${registry.repository}#`;
    const signal = AbortSignal.timeout(15_000);
    const [{ paths, sizes }, index] = await Promise.all([
      registry.componentIndex
        ? Promise.resolve({ paths: [] as string[], sizes: new Map<string, number>() })
        : repoTree(registry),
      registry.componentIndex
        ? read(`${raw}${registry.componentIndex}`, 2_000_000, signal).then((text) =>
            componentIndexSchema.parse(JSON.parse(text)),
          )
        : Promise.resolve(null),
    ]);
    const details = new Map<
      string,
      { manifest?: z.infer<typeof manifestSchema>; parts: PluginCompleteness | null }
    >();
    const queue = [...entries];
    const workers = Array.from({ length: MANIFEST_CONCURRENCY }, async () => {
      for (let entry = queue.shift(); entry; entry = queue.shift()) {
        const dir = entry.installedSource.startsWith(prefix)
          ? entry.installedSource.slice(prefix.length)
          : null;
        const manifestText = dir
          ? await cachedText(`${raw}${dir}/${registry.manifest}`, 64_000, signal)
          : undefined;
        const manifest = manifestText ? parseManifest(manifestText) : undefined;
        let parts: PluginCompleteness | null = null;
        if (index) {
          const indexed = index.plugins[entry.name];
          const pin = /@([a-f0-9]{40})/.exec(entry.source)?.[1];
          // The index describes one pinned commit; a different pin may have different parts.
          if (indexed && (!pin || indexed.sha === pin)) parts = classifyIndexed(indexed.components);
        } else if (dir) {
          const own = paths
            .filter((path) => path.startsWith(`${dir}/`))
            .map((path) => path.slice(dir.length + 1));
          const mcpPath = own.find((path) => path === "mcp.json" || path === ".mcp.json");
          const mcpText = mcpPath
            ? await cachedText(`${raw}${dir}/${mcpPath}`, 256_000, signal)
            : undefined;
          const ownSizes = new Map(
            own.map((path) => [path, sizes.get(`${dir}/${path}`) ?? 0] as const),
          );
          const classified = classifyPluginFiles(own, mcpText ?? undefined, ownSizes);
          parts = classified === "incomplete" ? null : classified;
        }
        details.set(entry.id, { manifest, parts });
      }
    });
    await Promise.all(workers);
    return entries.flatMap((entry) => {
      const detail = details.get(entry.id);
      if (!detail?.parts) return [];
      const dir = entry.installedSource.slice(prefix.length);
      const manifest = detail.manifest;
      return [
        {
          ...entry,
          ...detail.parts,
          displayName: manifest?.displayName ?? entry.displayName,
          category: entry.category ?? manifest?.category?.toLowerCase() ?? null,
          logo: manifest?.logo ? `${raw}${dir}/${manifest.logo.replace(/^\.\//, "")}` : null,
        },
      ];
    });
  }
  async function registryData(registry: Registry) {
    const cached = cache.get(registry.name);
    if (cached && cached.expires > Date.now()) return cached.data;
    // An expired catalog is still served while a fresh one loads, so browsing never waits on GitHub twice.
    if (cached) {
      void refresh(registry).catch(() => undefined);
      return cached.data;
    }
    return refresh(registry);
  }
  async function refresh(registry: Registry): Promise<ReturnType<typeof parsePluginMarketplace>> {
    const active = pending.get(registry.name);
    if (active) return active;
    const request = (async () => {
      const repo = new URL(registry.repository).pathname;
      const text = await read(
        `https://raw.githubusercontent.com${repo}/HEAD/${registry.path}`,
        2_000_000,
        AbortSignal.timeout(15_000),
      );
      if (Buffer.byteLength(text) > 2_000_000) throw new Error("Marketplace index is too large");
      const parsed = parsePluginMarketplace(text, registry);
      const entries = await withDetails(registry, parsed.entries);
      const data = {
        entries,
        skipped: parsed.skipped + parsed.entries.length - entries.length,
      };
      cache.set(registry.name, { data, expires: Date.now() + CATALOG_TTL_MS });
      return data;
    })();
    pending.set(registry.name, request);
    try {
      return await request;
    } finally {
      pending.delete(registry.name);
    }
  }
  return {
    async catalog(query: string): Promise<PluginMarketplaceCatalog> {
      const results = await Promise.allSettled(REGISTRIES.map(registryData));
      const entries: PluginMarketplaceEntry[] = [];
      const unavailableRegistries: string[] = [];
      let skippedEntries = 0;
      for (const [i, result] of results.entries()) {
        if (result.status === "fulfilled") {
          entries.push(...result.value.entries);
          skippedEntries += result.value.skipped;
        } else unavailableRegistries.push(REGISTRIES[i]!.name);
      }
      const now = Date.now();
      return {
        entries: entries
          .filter((entry) => (unreadable.get(entry.source) ?? 0) <= now)
          .map((entry) => ({ ...entry, category: pluginCategory(entry) }))
          .filter((entry) => matchesPluginQuery(entry, query))
          .sort(comparePlugins),
        unavailableRegistries,
        skippedEntries,
      };
    },
    /** A listed plugin that fails to preview, or would install only partly, leaves browse for a while. */
    markUnreadable(source: string) {
      unreadable.set(source, Date.now() + MANIFEST_TTL_MS);
    },
    clearUnreadable(source: string) {
      unreadable.delete(source);
    },
  };
}
