import { describe, expect, it } from "vitest";
import { inferBotRoleFromName, inferBotRoleRename } from "./bot-role-seed.js";

describe("bot role bootstrapping from names", () => {
  it.each([
    ["リサーチ統括", "リサーチ統括・タスク管理"],
    ["一次資料調査", "一次資料・原典リサーチ"],
    ["広域調査", "広域・探索リサーチ"],
    ["批判的思考", "批判的検証・反証"],
    ["出典監査", "出典・根拠監査"],
    ["株探索", "株式・企業分析"],
    ["Code Reviewer", "コードレビュー・品質監査"],
    ["医療調査", "専門リサーチ"],
    ["データ分析", "専門分析"],
  ])("infers a concrete editable role for %s", (name, title) => {
    const seed = inferBotRoleFromName(name);
    expect(seed?.title).toBe(title);
    expect(seed?.description.length).toBeGreaterThan(12);
    expect(seed?.instructions.length).toBeGreaterThan(80);
  });
  it.each(["New Bot", "田中", "Alice", "", "助手", "Team5", "😀"])(
    "does not hallucinate expertise from ambiguous name %s",
    (name) => {
      expect(inferBotRoleFromName(name)).toBeNull();
    },
  );
  it.each(["__Skeptic9000__", "__CodeReviewer__", "  __Skeptic9000__  "])(
    "rejects opaque role-like identifiers: %s",
    (name) => {
      expect(inferBotRoleFromName(name)).toBeNull();
    },
  );
  it("changes only fields still matching the autogenerated old role", () => {
    const old = inferBotRoleFromName("広域調査")!;
    const rename = inferBotRoleRename({ name: "広域調査", ...old }, "出典監査", {});
    expect(rename).toEqual(inferBotRoleFromName("出典監査"));
  });
  it("preserves custom instructions and explicit edits on rename", () => {
    const old = inferBotRoleFromName("広域調査")!;
    const rename = inferBotRoleRename(
      { name: "広域調査", ...old, instructions: "My personal procedure" },
      "出典監査",
      { description: "My manual description" },
    );
    expect(rename.title).toBe(inferBotRoleFromName("出典監査")!.title);
    expect(rename.description).toBeUndefined();
    expect(rename.instructions).toBeUndefined();
  });
  it("fills empty role fields after rename but does not reassign vague names", () => {
    expect(
      inferBotRoleRename(
        { name: "New Bot", title: "", description: "", instructions: "" },
        "一次資料調査",
        {},
      ),
    ).toEqual(inferBotRoleFromName("一次資料調査"));
    expect(
      inferBotRoleRename(
        { name: "一次資料調査", ...inferBotRoleFromName("一次資料調査")! },
        "Alex",
        {},
      ),
    ).toEqual({});
  });
});
