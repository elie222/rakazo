export function Icon({ name, label, size }: { name?: string; label?: string; size?: number }) {
  if (!isPageIcon(name)) return null;
  const Drawn = ICONS[name];
  const named = typeof label === "string" && label.trim() ? label.trim() : undefined;
  const px = typeof size === "number" && Number.isFinite(size) && size > 0 ? size : undefined;
  return (
    <Drawn
      className="rk-icon"
      data-mirror={MIRRORED_ICONS.has(name) || undefined}
      width={px ?? "1em"}
      height={px ?? "1em"}
      strokeWidth={2.25}
      {...(named ? { role: "img", "aria-label": named } : { "aria-hidden": true })}
    />
  );
}

export function Glyph({ name }: { name: unknown }) {
  return isPageIcon(name) ? (
    <span className="rk-glyph">
      <Icon name={name} />
    </span>
  ) : null;
}

