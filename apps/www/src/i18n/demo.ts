const DEMO_TEXT: Partial<Record<Locale, Record<string, string>>> = {
  zh: ZH_DEMO_TEXT,
  ja: JA_DEMO_TEXT,
};

export function demoText(locale: Locale, source: string, values: DemoValues = {}): string {
  const template = DEMO_TEXT[locale]?.[source] ?? source;
  return template.replace(/\{([A-Za-z0-9_]+)\}/g, (match, key: string) =>
    Object.hasOwn(values, key) ? String(values[key]) : match,
  );
}

export function getDemoBots(locale: Locale): DemoBot[] {
  const text = (value: string) => demoText(locale, value);
  return DEMO_BOTS.map((bot) => ({
    ...bot,
    time: text(bot.time),
    preview: text(bot.preview),
    routines: bot.routines.map((routine) => ({
      ...routine,
      name: text(routine.name),
      instruction: routine.instruction ? text(routine.instruction) : routine.instruction,
      // Leave `when` in English so ProductDemo's parseWhen can edit schedules.
      runs: routine.runs?.map((run) => ({
        ...run,
        text: text(run.text),
        time: text(run.time),
      })),
    })),
    screen: {
      ...bot.screen,
      title: text(bot.screen.title),
      lines: bot.screen.lines.map(text),
    },
    thread: bot.thread.map((message) =>
      message.type === "card"
        ? {
            ...message,
            lines: message.lines.map((line) => ({ k: text(line.k), v: text(line.v) })),
          }
        : message.type === "typing"
          ? message
          : { ...message, text: text(message.text) },
    ),
    reply: text(bot.reply),
  }));
}
